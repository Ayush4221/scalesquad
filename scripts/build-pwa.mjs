import { readFile, writeFile } from 'node:fs/promises';
import ts from 'typescript';
import { palette } from '../src/styles/palette.ts';

const offline = (await readFile('src/pwa/offline.html', 'utf8')).replace(
  /__PALETTE_(INK|TEXT|LIME)__/g,
  (_, name) => palette[name.toLowerCase()],
);
await writeFile('public/offline.html', `<!-- Generated by scripts/build-pwa.mjs. -->\n${offline}`);

const logic = ts
  .transpileModule(await readFile('src/pwa/swLogic.ts', 'utf8'), {
    compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext },
  })
  .outputText.replace(/^export /gm, '');
await writeFile(
  'public/sw.js',
  `/* Generated by scripts/build-pwa.mjs. Edit src/pwa instead. */\n${logic}\n${await readFile('src/pwa/worker.js', 'utf8')}`,
);
