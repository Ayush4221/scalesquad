import { readFile, writeFile } from 'node:fs/promises';
import ts from 'typescript';
const logic = ts
  .transpileModule(await readFile('src/pwa/swLogic.ts', 'utf8'), {
    compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext },
  })
  .outputText.replace(/^export /gm, '');
await writeFile(
  'public/sw.js',
  `/* Generated by scripts/build-pwa.mjs. Edit src/pwa instead. */\n${logic}\n${await readFile('src/pwa/worker.js', 'utf8')}`,
);
