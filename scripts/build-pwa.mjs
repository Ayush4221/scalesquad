import { readFile, writeFile } from 'node:fs/promises';
import ts from 'typescript';
import { palette } from '../src/styles/palette.ts';
import { pwaStrings } from '../src/constants/strings/pwa.ts';

const escapeHtml = (value) =>
  value.replace(
    /[&<>"']/g,
    (char) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[char],
  );
const offline = (await readFile('src/pwa/offline.html', 'utf8'))
  .replace(/__TEXT_(\w+)__/g, (_, key) => escapeHtml(pwaStrings[key]))
  .replace(/__PALETTE_(INK|TEXT|LIME)__/g, (_, name) => palette[name.toLowerCase()]);
await writeFile('public/offline.html', `<!-- Generated by scripts/build-pwa.mjs. -->\n${offline}`);

const inlineModule = (source) =>
  ts
    .transpileModule(source, {
      compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext },
    })
    .outputText.replace(/^export /gm, '');
const strings = (
  await Promise.all(
    ['common', 'pwa'].map(async (name) =>
      inlineModule(await readFile(`src/constants/strings/${name}.ts`, 'utf8')),
    ),
  )
).join('\n');
const logic = ts
  .transpileModule(await readFile('src/pwa/swLogic.ts', 'utf8'), {
    compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext },
  })
  .outputText.replace(
    /^import \{ pwaStrings \} from ['"]@\/constants\/strings\/pwa['"];\r?\n/gm,
    '',
  )
  .replace(/^export /gm, '');
await writeFile(
  'public/sw.js',
  `/* Generated by scripts/build-pwa.mjs. Edit src/pwa instead. */\n${strings}\n${logic}\n${await readFile('src/pwa/worker.js', 'utf8')}`,
);
