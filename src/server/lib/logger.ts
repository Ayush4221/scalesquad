import pino from 'pino';
export const redactionPaths = [
  'req.headers.cookie',
  'req.headers.authorization',
  'req.body',
  'sessionToken',
  'tokenHash',
  '*.sessionToken',
  '*.tokenHash',
  'cookie',
  'authorization',
  'token',
  'secret',
  'apiKey',
  'payload',
  'evidence',
  '*.token',
  '*.secret',
  '*.apiKey',
  '*.payload',
  '*.evidence',
  'access_token',
  'refresh_token',
  'id_token',
  'password',
  'newPassword',
  'currentPassword',
  'passwordHash',
  'endpoint',
  'p256dh',
  'auth',
  '*.password',
  '*.newPassword',
  '*.currentPassword',
  '*.passwordHash',
  '*.endpoint',
  '*.p256dh',
  '*.auth',
  'privateKey',
  '*.privateKey',
  '*.*.privateKey',
  ...[
    'AUTH_SECRET',
    'AUTH_GOOGLE_SECRET',
    'AUTH_GITHUB_SECRET',
    'NEXCONN_APP_SECRET',
    'VAPID_PRIVATE_KEY',
    'MAIL_API_KEY',
    'SMTP_URL',
    'DATABASE_URL',
    'DIRECT_URL',
  ].flatMap((key) => [key, `*.${key}`]),
];
export function createLogger(level = 'info', destination?: pino.DestinationStream) {
  const options: pino.LoggerOptions = {
    level,
    redact: { paths: redactionPaths, censor: '[Redacted]' },
    serializers: {
      err: (error: unknown) => ({ type: error instanceof Error ? error.name : 'Error' }),
    },
  };
  return destination ? pino(options, destination) : pino(options);
}
